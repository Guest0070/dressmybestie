def n_of(seconds: float) -> int:
    return max(1, int(round(seconds * SR)))


def times(seconds: float) -> np.ndarray:
    return np.arange(n_of(seconds)) / SR


def note(name: str) -> float:
    """'A4' -> 440.0. Sharps as '#'."""
    names = {"C": -9, "D": -7, "E": -5, "F": -4, "G": -2, "A": 0, "B": 2}
    semis = names[name[0]]
    rest = name[1:]
    if rest.startswith("#"):
        semis += 1
        rest = rest[1:]
    elif rest.startswith("b"):
        semis -= 1
        rest = rest[1:]
    octave = int(rest)
    return 440.0 * 2 ** ((semis + (octave - 4) * 12) / 12)


def osc(freq, seconds: float, kind: str = "sine", phase: float = 0.0) -> np.ndarray:
    """Oscillator; freq may be a scalar or a per-sample array (for sweeps)."""
    n = n_of(seconds)
    f = np.broadcast_to(np.asarray(freq, dtype=np.float64), (n,))
    ph = phase + 2 * np.pi * np.cumsum(f) / SR
    if kind == "sine":
        return np.sin(ph)
    if kind == "tri":
        return 2 / np.pi * np.arcsin(np.sin(ph))
    if kind == "saw":  # band-limited-ish: sum of 12 harmonics
        out = np.zeros(n)
        for k in range(1, 13):
            mask = (f * k) < SR / 2.2
            out += mask * np.sin(k * ph) / k
        return out * 0.6
    if kind == "square":
        out = np.zeros(n)
        for k in range(1, 14, 2):
            mask = (f * k) < SR / 2.2
            out += mask * np.sin(k * ph) / k
        return out * 0.8
    raise ValueError(kind)


def sweep(f0: float, f1: float, seconds: float, curve: str = "exp") -> np.ndarray:
    x = np.linspace(0, 1, n_of(seconds))
    if curve == "exp":
        return f0 * (f1 / f0) ** x
    return f0 + (f1 - f0) * x


def env(seconds: float, attack: float = 0.005, decay: float = 0.2, sustain: float = 0.0,
        release: float = 0.0, hold: float = 0.0) -> np.ndarray:
    """Attack, exponential decay towards sustain, hold, then exponential release."""
    n = n_of(seconds)
    t = np.arange(n) / SR
    a = np.clip(t / max(attack, 1e-4), 0, 1)
    d = sustain + (1 - sustain) * np.exp(-np.maximum(t - attack, 0) / max(decay, 1e-4))
    e = a * d
    if release > 0:
        start = attack + hold
        r = np.where(t > start, np.exp(-(t - start) / release), 1.0)
        e = e * r
    return e


def rng(seed: int) -> np.random.Generator:
    return np.random.default_rng(seed)


def noise(seconds: float, seed: int) -> np.ndarray:
    return rng(seed).uniform(-1, 1, n_of(seconds))


def band(x: np.ndarray, lo: float | None = None, hi: float | None = None, slope: float = 0.15) -> np.ndarray:
    """Zero-phase band filter with soft (log-domain) edges, done in the frequency domain."""
    spec = np.fft.rfft(x)
    f = np.fft.rfftfreq(len(x), 1 / SR) + 1e-9
    gain = np.ones_like(f)
    if lo:
        gain *= 1 / (1 + np.exp(-(np.log(f) - np.log(lo)) / slope))
    if hi:
        gain *= 1 / (1 + np.exp((np.log(f) - np.log(hi)) / slope))
    return np.fft.irfft(spec * gain, len(x))


def swept_band(x: np.ndarray, f_start: float, f_end: float, q: float = 0.35, chunks: int = 48) -> np.ndarray:
    """Band-pass whose centre moves over time (overlap-added chunks)."""
    n = len(x)
    out = np.zeros(n)
    hop = n // chunks
    win = np.hanning(hop * 2)
    for i in range(chunks):
        a = i * hop
        seg = x[a:a + hop * 2]
        if len(seg) < hop * 2:
            seg = np.pad(seg, (0, hop * 2 - len(seg)))
        frac = i / max(chunks - 1, 1)
        centre = f_start * (f_end / f_start) ** frac
        filt = band(seg * win, centre * (1 - q), centre * (1 + q), 0.12)
        end = min(n, a + hop * 2)
        out[a:end] += filt[: end - a]
    return out


def fm_bell(freq: float, seconds: float, ratio: float = 3.5, index: float = 2.0, decay: float = 0.6) -> np.ndarray:
    t = times(seconds)
    mod_env = np.exp(-t / (decay * 0.5))
    mod = index * mod_env * np.sin(2 * np.pi * freq * ratio * t)
    return np.sin(2 * np.pi * freq * t + mod) * env(seconds, 0.002, decay)


def pluck(freq: float, seconds: float, decay: float = 0.25, kind: str = "tri", bright: float = 6000) -> np.ndarray:
    tone = osc(freq, seconds, kind) * env(seconds, 0.003, decay)
    return band(tone, None, bright)


def reverb(x: np.ndarray, seconds: float = 0.8, mix: float = 0.18, seed: int = 99) -> np.ndarray:
    """Cheap plate: convolve with decaying, darkened noise. Output keeps the input length + tail."""
    t = times(seconds)
    ir = band(noise(seconds, seed), 200, 7000) * np.exp(-t / (seconds / 4))
    ir /= np.sqrt(np.sum(ir ** 2)) + 1e-9
    size = len(x) + len(ir) - 1
    nfft = 1 << (size - 1).bit_length()
    wet = np.fft.irfft(np.fft.rfft(x, nfft) * np.fft.rfft(ir, nfft), nfft)[:size]
    dry = np.pad(x, (0, size - len(x)))
    return dry * (1 - mix) + wet * mix * 1.5


def place(dest: np.ndarray, src: np.ndarray, at_seconds: float, gain: float = 1.0) -> None:
    a = int(round(at_seconds * SR))
    if a >= len(dest):
        return
    end = min(len(dest), a + len(src))
    dest[a:end] += src[: end - a] * gain


def canvas(seconds: float) -> np.ndarray:
    return np.zeros(n_of(seconds))


def sparkle(seconds: float, seed: int, count: int = 8, lo: float = 2500, hi: float = 6000) -> np.ndarray:
    r = rng(seed)
    out = canvas(seconds)
    for _ in range(count):
        f = r.uniform(lo, hi)
        place(out, fm_bell(f, 0.25, ratio=2.01, index=1.2, decay=0.08), r.uniform(0, seconds * 0.7),
              r.uniform(0.15, 0.4))
    return out


def chord(freqs, seconds: float, voice) -> np.ndarray:
    return sum(voice(f, seconds) for f in freqs) / len(freqs)


