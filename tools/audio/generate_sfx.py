# ------------------------------------------------------------------------------------------------
# Music loops. Rendered with a tail past the loop point; process_sfx.py folds the tail onto the
# start so the loop is seamless.
# ------------------------------------------------------------------------------------------------


def epiano(f: float, s: float) -> np.ndarray:
    return fm_bell(f, s, 1.0, 1.1, 0.7) * 0.8 + osc(f, s) * env(s, 0.003, 0.9) * 0.2


def render_loop(bpm: float, bars: int, pattern) -> tuple[np.ndarray, int]:
    beat = 60 / bpm
    loop_seconds = bars * 4 * beat
    tail = 2.0
    out = canvas(loop_seconds + tail)
    pattern(out, beat)
    return out, n_of(loop_seconds)


@recipe
def mu_lobby_loop():
    bpm = 100
    progression = [("F3", ("F4", "A4", "C5")), ("D3", ("D4", "F4", "A4")),
                   ("Bb2", ("Bb3", "D4", "F4")), ("C3", ("C4", "E4", "G4"))] * 2
    arp_r = rng(200)

    def pattern(out, beat):
        bar = 4 * beat
        for b, (root, triad) in enumerate(progression):
            at = b * bar
            freqs = [note(n) for n in triad]
            for k in (0.5, 1.5, 2.5, 3.5):  # off-beat chords
                place(out, chord(freqs, beat * 0.9, epiano), at + k * beat, 0.32)
            bass = band(osc(note(root), bar * 0.95, "tri"), None, 900) * env(bar * 0.95, 0.01, 0.8, 0.4, 0.1,
                                                                             hold=bar * 0.8)
            place(out, bass, at, 0.45)
            for step in range(8):  # gentle arpeggio
                f = freqs[(step + b) % 3] * 2
                if arp_r.random() < 0.8:
                    place(out, pluck(f, 0.3, 0.12, "tri", 5000), at + step * beat / 2, 0.16)
            for k in (0, 2):
                place(out, kick(0.3), at + k * beat, 0.35)
            for k in range(8):
                place(out, hihat(0.05, 210 + k), at + k * beat / 2, 0.08 if k % 2 else 0.05)

    out, loop_n = render_loop(bpm, len(progression), pattern)
    return reverb(out, 1.2, 0.18), {"bpm": bpm, "bars": len(progression), "loop_samples": loop_n}


@recipe
def mu_runway_loop():
    bpm = 118  # matches the built-in beat in Audio.luau
    progression = [("A2", ("A3", "C4", "E4")), ("F2", ("F3", "A3", "C4")),
                   ("C3", ("C4", "E4", "G4")), ("G2", ("G3", "B3", "D4"))] * 2

    def pattern(out, beat):
        bar = 4 * beat
        for b, (root, triad) in enumerate(progression):
            at = b * bar
            freqs = [note(n) for n in triad]
            for k in range(4):
                place(out, kick(0.32), at + k * beat, 0.6)
                place(out, hihat(0.25, 300 + k, open_=True), at + (k + 0.5) * beat, 0.12)
            for k in (1, 3):
                place(out, clap(310 + b), at + k * beat, 0.35)
            for k in range(8):  # off-beat bass
                if k % 2 == 1:
                    tone = band(osc(note(root), beat * 0.45, "saw"), None, 700) * env(beat * 0.45, 0.003, 0.12)
                    place(out, tone, at + k * beat / 2, 0.5)
            for k in (0, 1.5, 3):  # synth stabs, ducked after each kick
                stab = chord([f * 2 for f in freqs], beat * 0.4,
                             lambda f, s: band(osc(f, s, "saw"), 300, 4500) * env(s, 0.003, 0.08))
                place(out, stab, at + k * beat + 0.02, 0.22)
            pad = chord(freqs, bar, lambda f, s: band(osc(f, s, "saw"), 200, 2000)
                        * env(s, 0.15, 1.0, 0.7, 0.2, hold=s - 0.3))
            duck = 1 - 0.6 * np.exp(-(np.arange(len(pad)) / SR % beat) / 0.12)
            place(out, pad * duck, at, 0.12)

    out, loop_n = render_loop(bpm, len(progression), pattern)
    return reverb(out, 0.9, 0.12), {"bpm": bpm, "bars": len(progression), "loop_samples": loop_n}


