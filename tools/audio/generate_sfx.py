def kick(seconds: float = 0.38) -> np.ndarray:
    body = osc(sweep(140, 45, seconds), seconds) * env(seconds, 0.001, 0.12)
    click = band(noise(0.01, 1), 1500, 6000) * env(0.01, 0.0005, 0.003)
    out = body
    place(out, click, 0, 0.4)
    return np.tanh(out * 1.6) / np.tanh(1.6)


def hihat(seconds: float = 0.07, seed: int = 2, open_: bool = False) -> np.ndarray:
    length = 0.25 if open_ else seconds
    return band(noise(length, seed), 7000, None) * env(length, 0.0005, 0.08 if open_ else 0.018)


def clap(seed: int = 3) -> np.ndarray:
    out = canvas(0.3)
    for i, at in enumerate((0.0, 0.011, 0.022)):
        place(out, band(noise(0.02, seed + i), 900, 3500) * env(0.02, 0.0005, 0.006), at)
    place(out, band(noise(0.25, seed + 9), 900, 3000) * env(0.25, 0.001, 0.06), 0.03, 0.8)
    return out


