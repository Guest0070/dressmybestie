def write_wav(path: Path, samples: np.ndarray) -> None:
    peak = np.max(np.abs(samples)) or 1.0
    data = (samples / peak * 0.7 * 32767).astype("<i2")  # headroom; process_sfx normalises
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(data.tobytes())


def main(ids: list[str]) -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    wanted = [e for e in CATALOG if not ids or e["id"] in ids]
    missing = [e["id"] for e in wanted if e["id"] not in RECIPES]
    if missing:
        print("No recipe for:", ", ".join(missing))
        return 1
    for entry in wanted:
        result = RECIPES[entry["id"]]()
        extra = {}
        if isinstance(result, tuple):
            result, extra = result
        samples = np.asarray(result, dtype=np.float64)
        if not np.all(np.isfinite(samples)):
            print(f"{entry['id']}: non-finite samples")
            return 1
        write_wav(OUT / f"{entry['id']}.wav", samples)
        sidecar = {
            "id": entry["id"],
            "source": {
                "type": "procedural",
                "tool": "tools/audio/generate_sfx.py",
                "recipe": entry["id"],
                "generator_version": GENERATOR_VERSION,
            },
            "licence": {
                "name": "Original work (procedurally generated for this project)",
                "commercial_use": True,
                "attribution_required": False,
                "verified": True,
                "notes": "Synthesised from oscillators and seeded noise by this repository's script; "
                         "no samples or third-party material.",
            },
            **extra,
        }
        (OUT / f"{entry['id']}.json").write_text(json.dumps(sidecar, indent=2) + "\n", encoding="utf-8")
        print(f"generated {entry['id']}  {len(samples) / SR:.2f}s")
    return 0


